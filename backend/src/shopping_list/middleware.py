"""ASGI middleware.

Order, from outermost to innermost (set up in ``main.create_app``):

1. ``RequestContextMiddleware``: request ID, response headers, access log
2. ``JSONCORSMiddleware``: CORS
3. ``ErrorGuardMiddleware``: turns unexpected exceptions into ``INTERNAL_ERROR``
4. ``BodySizeLimitMiddleware``: ``PAYLOAD_TOO_LARGE``

This order makes sure that every response, including 500s and CORS preflight
rejections, is JSON and carries the CORS and ``X-Request-ID`` headers.
"""

import time
import uuid

from starlette.datastructures import Headers, MutableHeaders
from starlette.middleware.cors import CORSMiddleware
from starlette.responses import Response
from starlette.types import ASGIApp, Message, Receive, Scope, Send

from shopping_list.errors import ApiError, ErrorCode, error_response
from shopping_list.logging_setup import get_logger
from shopping_list.rate_limit import STATE_KEY, RateLimitDecision
from shopping_list.request_context import request_id_var

logger = get_logger("http")

_MAX_LOGGED_PATH = 200


def _loggable_path(path: str) -> str:
    """Keep attacker-controlled paths from breaking the log format."""
    safe = "".join(char if char.isprintable() else "?" for char in path)
    return safe[:_MAX_LOGGED_PATH]


class RequestContextMiddleware:
    """Assigns a request ID and adds ``X-Request-ID`` and ``RateLimit-*`` headers.

    The ID is always generated by the backend; a client-supplied ``X-Request-ID`` is
    ignored, so it can't be used to inject arbitrary values into the logs.
    """

    def __init__(self, app: ASGIApp) -> None:
        self.app = app

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return

        request_id = str(uuid.uuid4())
        token = request_id_var.set(request_id)
        # Same dict that `request.state` uses further down the stack.
        state: dict = scope.setdefault("state", {})
        status_code = 500
        started = time.perf_counter()

        async def send_with_headers(message: Message) -> None:
            nonlocal status_code
            if message["type"] == "http.response.start":
                status_code = message["status"]
                headers = MutableHeaders(scope=message)
                headers["X-Request-ID"] = request_id
                decision: RateLimitDecision | None = state.get(STATE_KEY)
                if decision is not None:
                    headers["RateLimit-Limit"] = str(decision.limit)
                    headers["RateLimit-Remaining"] = str(decision.remaining)
                    headers["RateLimit-Reset"] = str(decision.reset_seconds)
            await send(message)

        try:
            await self.app(scope, receive, send_with_headers)
        finally:
            logger.info(
                "%s %s -> %d (%.1f ms)",
                scope["method"],
                _loggable_path(scope["path"]),
                status_code,
                (time.perf_counter() - started) * 1000,
            )
            request_id_var.reset(token)


def _cors_headers(response: Response) -> dict[str, str]:
    return {k: v for k, v in response.headers.items() if k.lower().startswith("access-control-")}


class JSONCORSMiddleware(CORSMiddleware):
    """Starlette's CORS middleware, adapted so that no plain text response leaves the API.

    Accepted preflights get ``204 No Content``, rejected ones an ``ErrorResponse``.
    """

    def preflight_response(self, request_headers: Headers) -> Response:
        response = super().preflight_response(request_headers)
        if response.status_code < 400:
            allowed = Response(status_code=204)
            allowed.headers.update(_cors_headers(response))
            return allowed
        rejected = error_response(
            ErrorCode.VALIDATION_ERROR, "This cross-origin request is not allowed."
        )
        rejected.headers.update(_cors_headers(response))
        return rejected


class ErrorGuardMiddleware:
    """Last line of defence: any unhandled exception becomes ``500 INTERNAL_ERROR``.

    The exception is logged (with the request ID), but nothing about it is sent to
    the client.
    """

    def __init__(self, app: ASGIApp) -> None:
        self.app = app

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return

        response_started = False

        async def tracking_send(message: Message) -> None:
            nonlocal response_started
            if message["type"] == "http.response.start":
                response_started = True
            await send(message)

        try:
            await self.app(scope, receive, tracking_send)
        except Exception:
            logger.exception("Unhandled error while processing the request")
            if response_started:
                raise
            await error_response(ErrorCode.INTERNAL_ERROR)(scope, receive, send)


class BodySizeLimitMiddleware:
    """Rejects request bodies larger than ``max_bytes`` with ``413 PAYLOAD_TOO_LARGE``.

    A too large ``Content-Length`` is rejected before the body is read. Bodies without
    (or with a wrong) ``Content-Length`` are counted while they are read.
    """

    def __init__(self, app: ASGIApp, max_bytes: int) -> None:
        self.app = app
        self.max_bytes = max_bytes

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return

        content_length = Headers(scope=scope).get("content-length")
        if (
            content_length is not None
            and content_length.isdigit()
            and int(content_length) > self.max_bytes
        ):
            await error_response(ErrorCode.PAYLOAD_TOO_LARGE)(scope, receive, send)
            return

        received = 0

        async def limited_receive() -> Message:
            nonlocal received
            message = await receive()
            if message["type"] == "http.request":
                received += len(message.get("body", b""))
                if received > self.max_bytes:
                    # Raised inside `await request.body()`, handled like any ApiError.
                    raise ApiError(ErrorCode.PAYLOAD_TOO_LARGE)
            return message

        await self.app(scope, limited_receive, send)
